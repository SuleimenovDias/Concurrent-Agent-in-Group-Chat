import { expect, test } from '@playwright/test'

test('main StudyBuddy run uses backend decisions and publishes the final pitch', async ({page}) => {
  test.setTimeout(90_000)
  await page.goto('/')
  await expect(page.getByRole('heading', {name: 'StudyBuddy Team'})).toBeVisible()
  await page.getByRole('button', {name: 'Start Demo'}).click()
  await expect(page.getByText('Morning guys!', {exact: false})).toBeVisible()
  await expect(page.getByText('Use updated version', {exact: false}).first()).toBeVisible({timeout: 35_000})
  await page.getByRole('button', {name: 'Use updated version'}).first().click()
  await expect(page.getByText('Jack chose the updated feature suggestions.')).toBeVisible()
  await expect(page.getByText('Perfect. I’ll handle the slides.', {exact: false})).toBeVisible({timeout: 35_000}).catch(async () => {
    await expect(page.getByText("Perfect. I'll handle the slides.", {exact: false})).toBeVisible()
  })
  await expect(page.getByText('You’re all caught up')).toBeVisible({timeout: 20_000})
  await expect(page.getByText('Built from the selected findings:')).toBeVisible()
  await expect(page.getByText(/Three exam-season features/).first()).toBeVisible()
  await expect(page.getByTestId('chat-message').last()).toContainText("Perfect. I'll handle the slides.")
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({path: 'screenshots/studybuddy-phone.png', fullPage: true})
})

test('cancellation reports the actual backend result', async ({page}) => {
  test.setTimeout(45_000)
  await page.goto('/')
  await page.getByRole('button', {name: 'Demo menu'}).click()
  await page.getByRole('button', {name: /Changing course/}).click()
  await page.getByRole('button', {name: 'Demo menu'}).click()
  await page.getByRole('button', {name: /Start Demo/}).last().click()
  await expect(page.getByText(/checklist for launching StudyBuddy/)).toBeVisible({timeout: 15_000})
  await expect(page.getByRole('status')).toContainText(/stopped the checklist|already finished/, {timeout: 20_000})
})

test('ambiguous follow-up asks for a task and accepts clarification', async ({page}) => {
  test.setTimeout(45_000)
  await page.goto('/')
  await page.getByRole('button', {name: 'Demo menu'}).click()
  await page.getByRole('button', {name: /Which one/}).click()
  await page.getByRole('button', {name: 'Demo menu'}).click()
  await page.getByRole('button', {name: /Start Demo/}).last().click()
  await expect(page.getByText(/Which earlier task did you mean/)).toBeVisible({timeout: 25_000})
  await page.getByRole('button', {name: 'Tagline', exact: true}).click()
  await expect(page.getByRole('textbox', {name: 'Message'})).toHaveValue(/tagline task/)
  await page.getByRole('button', {name: 'Send message'}).click()
  await expect(page.getByText(/update my StudyBuddy tagline task/)).toBeVisible()
})

test('pause, single step, and restart preserve a usable phone', async ({page}) => {
  test.setTimeout(45_000)
  await page.goto('/')
  await page.getByRole('button', {name: 'Start Demo'}).click()
  await page.getByRole('button', {name: 'Pause demo'}).click()
  await expect(page.getByText('Paused', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'Next message'}).click()
  await expect(page.getByText('Morning guys!', {exact: false})).toBeVisible()
  await page.getByRole('button', {name: 'Demo menu'}).click()
  await page.getByRole('button', {name: 'Restart Demo'}).click()
  await expect(page.getByText('1 / 14')).toBeVisible({timeout: 10_000})
})
